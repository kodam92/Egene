-- 신규 히스토리맵 추가
INSERT INTO ESO_SRM_WF (
    WFF_ID,
    WFF_SRC_ID,
    WFF_REG_DTTM,
    WFF_TAS_ID,
    WFF_NEXT_TAS_ID,
    WFF_ORG_ID,
    WFF_DPT_ID,
    WFF_EMP_ID,
    WFF_CURRENT,
    WFF_TITLE_CD,
    WFF_DUTY_CD
)
SELECT
    CONCAT(?, '_', (@ROWNUM := @ROWNUM + 1)) AS WFF_ID,
    ES.SRM_ID,
    DATE_FORMAT(
        DATE_ADD(
            NOW(),
            INTERVAL (
                SELECT COUNT(*) - 1
                  FROM ESO_SRM_WF WF_PREV
                 WHERE WF_PREV.WFF_SRC_ID = WF.WFF_SRC_ID
                   AND WF_PREV.WFF_ID <= WF.WFF_ID
            ) * 10 SECOND
        ),
        '%Y%m%d%H%i%s'
    ) AS WFF_REG_DTTM,
    WF.WFF_TAS_ID,
    WF.WFF_NEXT_TAS_ID,
    WF.WFF_ORG_ID,
    WF.WFF_DPT_ID,
    WF.WFF_EMP_ID,
    CASE
        WHEN (
            SELECT COUNT(*)
              FROM ESO_SRM_WF WF_PREV
             WHERE WF_PREV.WFF_SRC_ID = WF.WFF_SRC_ID
               AND WF_PREV.WFF_ID <= WF.WFF_ID
        ) = 2 THEN 1
        ELSE WF.WFF_CURRENT
    END AS WFF_CURRENT,
    WF.WFF_TITLE_CD,
    WF.WFF_DUTY_CD
  FROM (SELECT @ROWNUM := 0) R
  CROSS JOIN ESO_SRM_WF WF
  JOIN ESO_SRM ES
    ON WF.WFF_SRC_ID = ES.SRM_SRC_ID
 WHERE WF.WFF_SRC_ID = ?
   AND WF.WFF_ID < (
         SELECT MAX(WF_LAST.WFF_ID)
           FROM ESO_SRM_WF WF_LAST
          WHERE WF_LAST.WFF_SRC_ID = ?
       )
 
__END__

